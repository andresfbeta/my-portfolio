const DEFAULT_LANG = "en";
const LANG_STORAGE_KEY = "portfolio-lang";

// Page-specific dictionaries (project case studies) register their own
// keys here rather than being appended to the shared one above.
function registerTranslations(extra) {
  Object.keys(extra).forEach((lang) => {
    if (!translations[lang]) return;
    Object.assign(translations[lang], extra[lang]);
  });
}
window.registerTranslations = registerTranslations;

function getTranslation(key, fallback) {
  const lang = document.documentElement.getAttribute("data-lang") || DEFAULT_LANG;
  const dict = translations[lang] || translations[DEFAULT_LANG];
  if (dict && dict[key] !== undefined) return dict[key];
  if (translations.en && translations.en[key] !== undefined) return translations.en[key];
  return fallback !== undefined ? fallback : key;
}
window.getTranslation = getTranslation;

// Private browsing and blocked-storage modes throw on access, and the
// language toggle must keep working regardless.
function readStoredLang() {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY);
  } catch {
    return null;
  }
}

function storeLang(lang) {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    /* preference simply won't survive the navigation */
  }
}

function applyTranslations(lang) {
  const dict = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const pairs = el.getAttribute("data-i18n-attr").split(";");
    pairs.forEach((pair) => {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (attr && dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });
  document.documentElement.setAttribute("lang", lang);
  document.documentElement.setAttribute("data-lang", lang);

  fitRingText(dict["hero.ring"]);

  const esBtn = document.querySelector('[data-lang-option="es"]');
  const enBtn = document.querySelector('[data-lang-option="en"]');
  if (esBtn && enBtn) {
    esBtn.setAttribute("aria-pressed", String(lang === "es"));
    enBtn.setAttribute("aria-pressed", String(lang === "en"));
  }

  document.dispatchEvent(new CustomEvent("i18n:change", { detail: { lang } }));
}

function setLanguage(lang) {
  if (lang !== "en" && lang !== "es") return;
  applyTranslations(lang);
  storeLang(lang);
}

// Ring path is a circle of radius 177.5 in the SVG's own viewBox units
// (see index.html #ringPath) — this holds regardless of rendered size.
const RING_CIRCUMFERENCE = 2 * Math.PI * 177.5;

function fitRingText(phrase) {
  const ringPath = document.querySelector(".ring-text textPath");
  if (!ringPath || !phrase) return;

  ringPath.removeAttribute("textLength");
  ringPath.textContent = phrase;
  const oneRepLength = ringPath.getComputedTextLength();
  if (!oneRepLength) return;

  const repeats = Math.max(1, Math.ceil(RING_CIRCUMFERENCE / oneRepLength));
  ringPath.textContent = phrase.repeat(repeats);
  ringPath.setAttribute("textLength", RING_CIRCUMFERENCE);
  ringPath.setAttribute("lengthAdjust", "spacingAndGlyphs");
}

document.addEventListener("DOMContentLoaded", () => {
  const stored = readStoredLang();
  applyTranslations(translations[stored] ? stored : DEFAULT_LANG);

  document.querySelectorAll("[data-lang-option]").forEach((btn) => {
    btn.addEventListener("click", () => setLanguage(btn.getAttribute("data-lang-option")));
  });

  // Re-fit once the web font is actually loaded — glyph widths measured
  // against a fallback font would throw off the repeat count.
  if (document.fonts && document.fonts.ready) {
    document.fonts.ready.then(() => {
      fitRingText(translations[document.documentElement.getAttribute("data-lang")]["hero.ring"]);
    });
  }
});
